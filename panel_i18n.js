const storageKey='eh-panel-language';
const supported=value=>value==='en'||value==='zh-CN';
function savedLanguage(){
 // A host-only cookie survives the launcher's changing loopback port. It stores
 // only this non-sensitive allowlisted preference, never account or access data.
 try{
  for(const part of String(root.document?.cookie||'').split(';')){
   const index=part.indexOf('=');
   if(index<0||part.slice(0,index).trim()!==storageKey)continue;
   const value=part.slice(index+1).trim();
   if(supported(value))return value;
  }
 }catch(_){}
 // Migrate preferences saved by clients that used origin-specific localStorage.
 try{const value=root.localStorage?.getItem(storageKey);if(supported(value))return value;}catch(_){}
 return null;
}
let language=savedLanguage()||(root.navigator?.language?.toLowerCase().startsWith('en')?'en':'zh-CN');

function t(key,params={}){
 const text=language==='en'&&Object.hasOwn(english,key)?english[key]:String(key);
 return text.replace(/\{(\w+)\}/g,(token,name)=>Object.hasOwn(params,name)?String(params[name]):token);
}
function setLanguage(next){
 if(!supported(next))throw new RangeError('Unsupported interface language');
 language=next;
 try{if(root.document)root.document.cookie=storageKey+'='+next+'; Path=/; SameSite=Strict; Max-Age=31536000';}catch(_){}
 try{root.localStorage?.setItem(storageKey,next);}catch(_){}
 if(root.document?.documentElement)root.document.documentElement.lang=next;
 return next;
}
function apply(doc=root.document){
 if(!doc)return;
 if(doc.documentElement)doc.documentElement.lang=language;
 // These markers are authored in panel.html. No whole-page traversal/replacement.
 for(const node of doc.querySelectorAll('[data-i18n]'))node.textContent=t(node.getAttribute('data-i18n'));
 for(const name of ['placeholder','title','aria-label'])for(const node of doc.querySelectorAll('[data-i18n-'+name+']'))node.setAttribute(name,t(node.getAttribute('data-i18n-'+name)));
}
root.EHPanelI18n=Object.freeze({t,setLanguage,getLanguage:()=>language,apply});
